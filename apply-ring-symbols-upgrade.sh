#!/usr/bin/env bash
set -euo pipefail

TARGET_ROOT="${1:-.}"
PACKAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PATCH_DIR="$PACKAGE_DIR/patches"
EMBEDDED_PATCH_DIR=""
CACHE_BUST="ring-symbols-upgrade-$(date +%Y%m%d%H%M%S)"

cleanup_embedded_patches() {
  if [[ -n "$EMBEDDED_PATCH_DIR" && -d "$EMBEDDED_PATCH_DIR" ]]; then
    rm -rf "$EMBEDDED_PATCH_DIR"
  fi
}
trap cleanup_embedded_patches EXIT

extract_embedded_patch() {
  local marker="$1"
  local output="$2"
  INSTALLER_PATH="$0" MARKER="$marker" OUTPUT_PATCH="$output" python3 <<'PY'
from pathlib import Path
import base64
import os
import sys

installer = Path(os.environ["INSTALLER_PATH"])
marker = os.environ["MARKER"]
out = Path(os.environ["OUTPUT_PATCH"])
text = installer.read_text(encoding="utf-8", errors="replace")
begin = f"__{marker}_BASE64_BEGIN__"
end = f"__{marker}_BASE64_END__"
start = text.rfind(begin)
stop = text.rfind(end)
if start == -1 or stop == -1 or stop <= start:
    print(f"ERROR: embedded patch payload not found: {marker}", file=sys.stderr)
    sys.exit(1)
payload = "".join(text[start + len(begin):stop].split())
out.write_bytes(base64.b64decode(payload))
PY
}

prepare_patch_dir() {
  if [[ -f "$PATCH_DIR/dial.html.patch" && -f "$PATCH_DIR/dial9.html.patch" && -f "$PATCH_DIR/dial.js.patch" ]]; then
    return 0
  fi

  EMBEDDED_PATCH_DIR="$(mktemp -d)"
  PATCH_DIR="$EMBEDDED_PATCH_DIR/patches"
  mkdir -p "$PATCH_DIR"
  extract_embedded_patch "DIAL_HTML_PATCH" "$PATCH_DIR/dial.html.patch"
  extract_embedded_patch "DIAL9_HTML_PATCH" "$PATCH_DIR/dial9.html.patch"
  extract_embedded_patch "DIAL_JS_PATCH" "$PATCH_DIR/dial.js.patch"
}

prepare_patch_dir

cd "$TARGET_ROOT"

for file in retro/dial.html retro/dial9.html retro/js/dial.js; do
  if [[ ! -f "$file" ]]; then
    echo "ERROR: missing $file in $TARGET_ROOT" >&2
    exit 1
  fi
  if [[ ! -f "$file.bak-ring-symbols-upgrade" ]]; then
    cp "$file" "$file.bak-ring-symbols-upgrade"
  fi
  perl -0pi -e 's/\r\n/\n/g' "$file"
done

patch --forward -p0 < "$PATCH_DIR/dial.html.patch"
patch --forward -p0 < "$PATCH_DIR/dial9.html.patch"
patch --forward -p0 < "$PATCH_DIR/dial.js.patch"

for html in retro/dial.html retro/dial9.html; do
  perl -0pi -e "s#js/dial\\.js(?:\\?v=[^\"']*)?#js/dial.js?v=$CACHE_BUST#g" "$html"
done

find . \
  \( -name '__pycache__' -o -name '.cache' -o -name '.pytest_cache' \) \
  -type d -prune -exec rm -rf {} + 2>/dev/null || true

if command -v systemctl >/dev/null 2>&1; then
  for service in nginx apache2 lighttpd; do
    if systemctl is-active --quiet "$service"; then
      if [[ "$(id -u)" -eq 0 ]]; then
        systemctl reload "$service" || systemctl restart "$service" || true
      elif command -v sudo >/dev/null 2>&1; then
        sudo systemctl reload "$service" || sudo systemctl restart "$service" || true
      fi
    fi
  done
fi

echo "OK: ring/symbol upgrade applied."
echo "Web cache-busting token applied: $CACHE_BUST"
echo "Local project cache folders were removed when present."
echo "Backups: retro/dial.html.bak-ring-symbols-upgrade, retro/dial9.html.bak-ring-symbols-upgrade, retro/js/dial.js.bak-ring-symbols-upgrade"

